# File: core/algorithms/__init__.py
"""
Реализации алгоритмов для движка оптимизации.

Этот файл — "витрина" (агрегатор) алгоритмов: он импортирует конкретные реализации из
отдельных модулей и дальше реэкспортирует их как единый публичный интерфейс пакета
`core.algorithms`.

Зачем так сделано:
• удобный импорт: внешний код может писать `from core.algorithms import de_optimization`,
  не зная, что она лежит в файле `de.py`;
• единая точка правды: здесь явно видно, какие алгоритмы считаются "официальными";
• устойчивость структуры: можно переорганизовать внутренние файлы, не ломая импорты снаружи.
"""

# Импорт жадной диспетчеризации (greedy) — это базовый алгоритм нижнего уровня (dispatch),
# который строит почасовое расписание покрытия нагрузки (schedule) для заданного состава оборудования.
from .greedy import greedy_optimization

# Импорт оптимизации Grey Wolf Optimizer (GWO) — верхний уровень (sizing):
# подбирает тип/количество ВЭУ и АКБ, а оценку кандидата делает через greedy_optimization.
from .wolf import wolf_optimization

# Импорт Differential Evolution (DE) — верхний уровень (sizing):
# аналогично подбирает состав (тип/количество ВЭУ и АКБ), оценку делает через greedy_optimization.
from .de import de_optimization

# __all__ задает список имен, которые считаются "публичными" при импорте:
# `from core.algorithms import *`
# Важно: это не влияет на обычные импорты по имени, но помогает держать API чистым.
__all__ = [
    "greedy_optimization",  # базовая диспетчеризация (нижний уровень)
    "wolf_optimization",    # подбор состава через GWO (верхний уровень + вызовы greedy)
    "de_optimization",      # подбор состава через DE (верхний уровень + вызовы greedy)
]
