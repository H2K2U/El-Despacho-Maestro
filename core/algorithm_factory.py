# File: core/algorithm_factory.py
"""
Фабрика выбора алгоритмов оптимизации.

Назначение файла:
• дать единый "реестр" доступных алгоритмов верхнего уровня (greedy / wolf(GWO) / de(DE));
• возвращать вызываемую реализацию по строковому ключу (например, из конфигурации/GUI/CLI);
• иметь метод, который возвращает список поддерживаемых ключей для интерфейсов.

Важно по архитектуре:
• Все алгоритмы должны иметь совместимую сигнатуру по смыслу (принимать load_profile, дизеля, ГЭС, ВЭУ, АКБ,
  а также опциональные параметры: wind_speeds/wind_data, progress_cb и т.д.).
• Фабрика не знает внутренних деталей алгоритмов — она просто выдает функцию.
"""


from typing import Callable, Dict, List

# Импортируем конкретные реализации алгоритмов из пакета core.algorithms.
# Здесь это:
# • greedy_optimization — жадный диспетчер/оптимизация (в твоем проекте он еще и может работать как "база");
# • wolf_optimization — оптимизация методом серых волков (GWO) для подбора состава;
# • de_optimization — дифференциальная эволюция (DE) для подбора состава.
from core.algorithms import de_optimization, greedy_optimization, wolf_optimization


# Тип "AlgorithmCallable" — это просто псевдоним типа для удобства чтения.
# Мы говорим: "алгоритм" — это любая вызываемая сущность (функция), которая принимает любые аргументы (...),
# и возвращает какой-то объект.
#
# В идеале, если хочешь строгость, можно заменить object на OptimizationResult и согласовать сигнатуры.
# Но сейчас оставлено максимально гибко, чтобы фабрика не ломалась при расширении/разных kwargs.
AlgorithmCallable = Callable[..., object]


class AlgorithmFactory:
    """
    Фабрика выбора алгоритмов оптимизации.

    Паттерн "Factory" (упрощенный вариант):
    • внутри есть словарь: ключ -> функция-реализация;
    • есть метод get_algorithm(name), который отдает нужную функцию;
    • есть метод list_algorithms(), который показывает доступные ключи.

    Почему удобно:
    • в GUI/конфиге ты хранишь строку ('greedy'/'wolf'/'de');
    • в коде не надо писать if/elif на каждое название;
    • добавление нового алгоритма = добавить импорт + дописать одну строку в _ALGORITHMS.
    """

    # _ALGORITHMS — "реестр" алгоритмов.
    # Ключ — строка (например, то, что приходит из config/GUI),
    # Значение — функция, которую надо вызвать.
    #
    # Важно: все функции должны быть совместимы по интерфейсу вызова.
    # (Хотя бы по ключевым параметрам, которые реально будут прокидываться извне.)
    _ALGORITHMS: Dict[str, AlgorithmCallable] = {
        "greedy": greedy_optimization,
        "wolf": wolf_optimization,
        "de": de_optimization,
    }

    @classmethod
    def get_algorithm(cls, name: str) -> AlgorithmCallable:
        """
        Возвращает реализацию алгоритма по ключу.

        Аргументы:
        • name — строковый идентификатор алгоритма (например: "de", "wolf", "greedy").

        Возвращает:
        • функцию-алгоритм (AlgorithmCallable).

        Поведение по умолчанию (важная деталь):
        • если ключ неизвестен (name не в словаре), возвращаем greedy_optimization.
          Это "безопасный fallback": проект не падает, а работает базовым алгоритмом.
        """
        return cls._ALGORITHMS.get(name, greedy_optimization)

    @classmethod
    def list_algorithms(cls) -> List[str]:
        """
        Возвращает список поддерживаемых алгоритмов (их ключи).

        Использование:
        • заполнить dropdown/combobox в GUI;
        • валидировать конфиг;
        • вывести справку в CLI.
        """
        return list(cls._ALGORITHMS.keys())
